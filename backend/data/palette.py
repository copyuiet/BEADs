@dataclass
class BeadColor:
    code: str
    hex: str
    r: int
    g: int
    b: int
    lab: Optional[tuple] = field(default=None, repr=False)


def _hex_to_rgb(hex6: str):
    return int(hex6[0:2], 16), int(hex6[2:4], 16), int(hex6[4:6], 16)


def _build_all() -> List[BeadColor]:
    colors: List[BeadColor] = []
    for fam, hexes in FAMILY.items():
        for i, hex6 in enumerate(hexes.split(), start=1):
            r, g, b = _hex_to_rgb(hex6)
            colors.append(BeadColor(code=f"{fam}{i}", hex=f"#{hex6}", r=r, g=g, b=b))
    return colors


ALL: List[BeadColor] = _build_all()
BY_CODE: Dict[str, BeadColor] = {c.code: c for c in ALL}

_tier_cache: Dict[int, List[BeadColor]] = {}


def _codes_of(spec: str) -> List[BeadColor]:
    out: List[BeadColor] = []
    seen = set()
    for code in spec.split():
        if code in seen or code not in BY_CODE:
            continue
        seen.add(code)
        out.append(BY_CODE[code])
    return out


def get_tier(tier: int) -> List[BeadColor]:
    """取某个档位的色卡（返回列表副本）。tier = 291 时返回全部。"""
    if tier == 291:
        if 291 not in _tier_cache:
            _tier_cache[291] = list(ALL)
        return list(_tier_cache[291])
    if tier not in _tier_cache:
        spec = TIERS.get(tier, _T221)
        _tier_cache[tier] = _codes_of(spec)
    return list(_tier_cache[tier])


def tier_size(tier: int) -> int:
    return len(get_tier(tier))


def filter_by_codes(colors: Sequence[BeadColor], codes: Sequence[str]) -> List[BeadColor]:
    code_set = set(codes)
    return [c for c in colors if c.code in code_set]
